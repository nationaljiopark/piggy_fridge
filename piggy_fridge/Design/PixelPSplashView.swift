//
//  PixelPSplashView.swift
//  Piggy Fridge splash: the pixel "P" draws itself pixel by pixel.
//  Foot and stem stack up row by row from the bottom (each row left -> right),
//  then the bowl draws clockwise along the centre line into the curl.
//
//  Same timing as the AE comp P_PixelStep (fridge copy / P_PixelStep_build.jsx):
//    Progress 0 -> 100 from 0.20 s to 2.87 s (0.6x speed), first key linear, last key Easy Ease In,
//    then hold, fade out, and call onFinished.
//
//  Drop-in replacement for PigPeekSplashView (same `onFinished` closure):
//      PixelPSplashView { router.splashDone() }     // or { showSplash = false }
//
//  No image assets needed: the P is drawn from the exact 4.svg polygons, and each pixel cell
//  is a clip rectangle that switches on when the progress passes its position (`r`, 0...100).
//

import SwiftUI

struct PixelPSplashView: View {
    var background: Color = .white
    var ink: Color = Color(red: 0x1F / 255, green: 0x1A / 255, blue: 0x17 / 255)
    var onFinished: () -> Void = {}

    // Timing (seconds)
    private let drawStart = 0.2
    private let drawDuration = 1.6 / 0.6       // 0.6x speed -> 2.667 s
    private let holdUntil = 3.4
    private let fadeDuration = 0.3

    @State private var start = Date()
    @State private var done = false

    var body: some View {
        GeometryReader { geo in
            TimelineView(.animation(paused: done)) { context in
                let t = context.date.timeIntervalSince(start)
                let progress = Self.progress(t, start: drawStart, duration: drawDuration)
                let fade = t <= holdUntil ? 1.0 : max(0, 1 - (t - holdUntil) / fadeDuration)

                Canvas { ctx, size in
                    // Same framing as the 1080x1920 comp: 1 svg unit = width / 216, artboard centred.
                    let splashScale = 0.28   // splash art at 28% size (was 70%)
                    let k = size.width / 216 * splashScale
                    let ox = size.width / 2 - 75 * k
                    let oy = size.height / 2 - 85.5 * k
                    func pt(_ p: CGPoint) -> CGPoint { CGPoint(x: ox + p.x * k, y: oy + p.y * k) }

                    var clip = Path()
                    for c in PixelPData.cells where progress >= c.r {
                        clip.addRect(CGRect(x: ox + (c.x - 0.4) * k, y: oy + (c.y - 0.4) * k,
                                            width: (c.w + 0.8) * k, height: (c.h + 0.8) * k))
                    }
                    guard !clip.isEmpty else { return }

                    var glyph = Path()
                    for poly in PixelPData.polygons {
                        glyph.move(to: pt(poly[0]))
                        for p in poly.dropFirst() { glyph.addLine(to: pt(p)) }
                        glyph.closeSubpath()
                    }
                    ctx.clip(to: clip)
                    ctx.fill(glyph, with: .color(ink))
                }
                .opacity(fade)
            }
        }
        .background(background.ignoresSafeArea())
        .ignoresSafeArea()
        .accessibilityLabel("Piggy Fridge")
        .task {
            start = Date()
            try? await Task.sleep(nanoseconds: UInt64((holdUntil + fadeDuration) * 1_000_000_000))
            done = true
            onFinished()
        }
    }

    /// AE: key 1 linear, key 2 Easy Ease In (speed 0, influence 33.33%) -> cubic-bezier(1/3, 1/3, 2/3, 1).
    static func progress(_ t: Double, start: Double, duration: Double) -> Double {
        let u = min(max((t - start) / duration, 0), 1)
        var lo = 0.0, hi = 1.0, s = u
        for _ in 0..<30 {
            s = (lo + hi) / 2
            let x = 3 * (1 - s) * (1 - s) * s * (1.0 / 3) + 3 * (1 - s) * s * s * (2.0 / 3) + s * s * s
            if x < u { lo = s } else { hi = s }
        }
        let y = 3 * (1 - s) * (1 - s) * s * (1.0 / 3) + 3 * (1 - s) * s * s * 1.0 + s * s * s
        return y * 100
    }
}

